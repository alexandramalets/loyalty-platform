CREATE SEQUENCE customer_code_seq START WITH 104600;
CREATE SEQUENCE transaction_code_seq START WITH 1000;
CREATE SEQUENCE promotion_code_seq START WITH 100;
CREATE SEQUENCE level_code_seq START WITH 100;

CREATE TABLE staff_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    initials VARCHAR(8) NOT NULL,
    role VARCHAR(128) NOT NULL,
    phone VARCHAR(32),
    last_login TIMESTAMP,
    password_changed DATE
);

CREATE TABLE loyalty_level (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    threshold_points INTEGER NOT NULL CHECK (threshold_points >= 0),
    accrual_percent INTEGER NOT NULL CHECK (accrual_percent >= 0 AND accrual_percent <= 100),
    color VARCHAR(16) NOT NULL,
    effective_from DATE NOT NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    CONSTRAINT uq_loyalty_level_threshold UNIQUE (threshold_points)
);

CREATE TABLE customer (
    id VARCHAR(32) PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    phone VARCHAR(32) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('active', 'inactive', 'blocked')),
    registered DATE NOT NULL
);

CREATE TABLE loyalty_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(32) NOT NULL UNIQUE REFERENCES customer (id) ON DELETE CASCADE,
    level_id VARCHAR(64) NOT NULL REFERENCES loyalty_level (id),
    points INTEGER NOT NULL DEFAULT 0 CHECK (points >= 0),
    purchases INTEGER NOT NULL DEFAULT 0 CHECK (purchases >= 0),
    last_activity DATE
);

CREATE TABLE bonus_transaction (
    id VARCHAR(32) PRIMARY KEY,
    customer_id VARCHAR(32) NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    amount INTEGER NOT NULL,
    type VARCHAR(24) NOT NULL CHECK (type IN ('Начисление', 'Списание')),
    operation_date DATE NOT NULL,
    reason VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('done', 'processing', 'error', 'cancelled')),
    event_name VARCHAR(64) NOT NULL,
    purchase_amount INTEGER
);

CREATE INDEX idx_bonus_transaction_customer ON bonus_transaction (customer_id, operation_date DESC);

CREATE TABLE promotion (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('active', 'scheduled', 'paused', 'finished')),
    level_id VARCHAR(64) REFERENCES loyalty_level (id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    bonus_value NUMERIC(12, 2) NOT NULL CHECK (bonus_value >= 0),
    description VARCHAR(500) NOT NULL DEFAULT '',
    CONSTRAINT chk_promotion_period CHECK (start_date <= end_date)
);

CREATE TABLE program_settings (
    id INTEGER PRIMARY KEY,
    program_name VARCHAR(180) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    bonus_unit VARCHAR(32) NOT NULL,
    recalc_period VARCHAR(16) NOT NULL,
    session_minutes VARCHAR(8) NOT NULL,
    two_factor BOOLEAN NOT NULL DEFAULT FALSE,
    since VARCHAR(32) NOT NULL,
    bonus_lifetime VARCHAR(64) NOT NULL,
    next_recalc VARCHAR(64) NOT NULL,
    notice_system BOOLEAN NOT NULL DEFAULT TRUE,
    notice_email BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE level_transition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(32) NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    from_level_id VARCHAR(64) NOT NULL REFERENCES loyalty_level (id),
    to_level_id VARCHAR(64) NOT NULL REFERENCES loyalty_level (id),
    changed_at DATE NOT NULL
);

CREATE INDEX idx_level_transition_date ON level_transition (changed_at);
